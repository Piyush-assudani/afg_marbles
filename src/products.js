/* Inquiry Persistence Manager */
const INQUIRY_STORAGE_KEY = 'afg_marble_inquiries';

export function saveInquiry(data) {
  const existing = getSavedInquiries();
  const id = 'AFG-' + new Date().getFullYear() + '-' + Math.floor(1000 + Math.random() * 9000);
  const newEntry = {
    id,
    timestamp: new Date().toISOString(),
    ...data
  };
  existing.unshift(newEntry);
  try {
    localStorage.setItem(INQUIRY_STORAGE_KEY, JSON.stringify(existing));
  } catch (e) {
    console.warn('localStorage save failed', e);
  }
  return newEntry;
}

export function getSavedInquiries() {
  try {
    const raw = localStorage.getItem(INQUIRY_STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch (e) {
    return [];
  }
}
